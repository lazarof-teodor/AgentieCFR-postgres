-- Schema bazei agentie_cfr (PostgreSQL 14+), aliniata cu DAO-urile din proiect.
-- Creeaza intai baza: CREATE DATABASE agentie_cfr;  apoi ruleaza scriptul conectat la ea.
-- Scriptul sterge tabelele existente din agentie_cfr (si datele din ele) si le recreeaza.

DROP TABLE IF EXISTS Bilet, Cursa, Loc, Vagon, Tren, Ruta, Statie, Client, Utilizator, Rol, numere CASCADE;

CREATE TABLE Rol (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE Utilizator (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL UNIQUE,
    parola_hash VARCHAR(100) NOT NULL,
    nume        VARCHAR(100) NOT NULL,
    prenume     VARCHAR(100) NOT NULL,
    rol_id      INT NOT NULL REFERENCES Rol(id),
    activ       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE Client (
    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume      VARCHAR(100) NOT NULL,
    prenume   VARCHAR(100) NOT NULL,
    email     VARCHAR(150),
    telefon   VARCHAR(20),
    categorie VARCHAR(50)
);

CREATE TABLE Statie (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume VARCHAR(100) NOT NULL,
    oras VARCHAR(100) NOT NULL
);

CREATE TABLE Ruta (
    id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statie_plecare_id INT NOT NULL REFERENCES Statie(id),
    statie_sosire_id  INT NOT NULL REFERENCES Statie(id),
    durata_estimata   TIME
);

CREATE TABLE Tren (
    id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numar  VARCHAR(20) NOT NULL UNIQUE,
    tip    VARCHAR(50) NOT NULL
);

CREATE TABLE Vagon (
    id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tren_id            INT NOT NULL REFERENCES Tren(id) ON DELETE CASCADE,
    numar_vagon        INT NOT NULL,
    clasa              VARCHAR(20) NOT NULL,
    nr_locuri          INT NOT NULL,
    multiplicator_pret DECIMAL(4,2) NOT NULL DEFAULT 1.00,
    UNIQUE (tren_id, numar_vagon)
);

CREATE TABLE Loc (
    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vagon_id  INT NOT NULL REFERENCES Vagon(id) ON DELETE CASCADE,
    numar_loc INT NOT NULL,
    UNIQUE (vagon_id, numar_loc)
);

CREATE TABLE Cursa (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tren_id     INT NOT NULL REFERENCES Tren(id),
    ruta_id     INT NOT NULL REFERENCES Ruta(id),
    data        DATE NOT NULL,
    ora_plecare TIME NOT NULL,
    ora_sosire  TIME NOT NULL,
    pret_baza   DECIMAL(10,2) NOT NULL
);

CREATE TABLE Bilet (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cursa_id      INT NOT NULL REFERENCES Cursa(id),
    loc_id        INT NOT NULL REFERENCES Loc(id),
    client_id     INT NOT NULL REFERENCES Client(id),
    utilizator_id INT NOT NULL REFERENCES Utilizator(id),
    pret          DECIMAL(10,2) NOT NULL,
    data_emitere  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status        VARCHAR(20) NOT NULL DEFAULT 'activ',
    loc_activ     INT GENERATED ALWAYS AS (CASE WHEN status = 'activ' THEN loc_id END) STORED,
    UNIQUE (cursa_id, loc_activ)
);

CREATE TABLE numere (
    x INT PRIMARY KEY
);

